_qa_pipeline = None
_embedder = None


def get_embedder():
    """
    Lazy loader for SentenceTransformer dense embedding model.
    """
    global _embedder
    if _embedder is None:
        try:
            _embedder = SentenceTransformer('all-MiniLM-L6-v2', local_files_only=True)
        except Exception:
            _embedder = SentenceTransformer('all-MiniLM-L6-v2')
    return _embedder


def get_qa_pipeline():
    """
    Lazy loader for QA transformer pipeline.
    """
    global _qa_pipeline
    if _qa_pipeline is None:
        try:
            _qa_pipeline = pipeline(
                "question-answering",
                model="distilbert-base-cased-distilled-squad",
                local_files_only=True
            )
        except Exception:
            _qa_pipeline = pipeline(
                "question-answering",
                model="distilbert-base-cased-distilled-squad"
            )
    return _qa_pipeline


def clean_pdf_text(text):
    if not text:
        return ""
    text = re.sub(r'(\w+)-\n(\w+)', r'\1\2', text)
    text = re.sub(r'[ \t]+', ' ', text)
    return text.strip()


def extract_document_paragraphs(text, max_words=140, overlap_words=30):
    cleaned = clean_pdf_text(text)
    if not cleaned:
        return []

    raw_paragraphs = [p.strip() for p in cleaned.split('\n\n') if len(p.strip()) > 15]

    chunks = []
    if raw_paragraphs and len(raw_paragraphs) >= 3:
        for p in raw_paragraphs:
            words = p.split()
            if len(words) <= max_words:
                chunks.append(p)
            else:
                step = max_words - overlap_words
                for i in range(0, len(words), step):
                    cw = words[i:i + max_words]
                    if len(cw) > 15:
                        chunks.append(" ".join(cw))
    else:
        norm_text = re.sub(r'\s+', ' ', cleaned)
        words = norm_text.split()
        if len(words) <= max_words:
            return [norm_text]

        step = max_words - overlap_words
        for i in range(0, len(words), step):
            cw = words[i:i + max_words]
            if len(cw) > 15:
                chunks.append(" ".join(cw))

    return chunks


def get_keyword_overlap_factor(question, paragraph):
    stop_words = {
        'the', 'a', 'an', 'is', 'are', 'was', 'were', 'what', 'which',
        'who', 'how', 'for', 'of', 'in', 'on', 'to', 'and', 'this',
        'that', 'did', 'does', 'do', 'by', 'at', 'with', 'from', 'in'
    }
    q_words = set(re.findall(r'\w+', question.lower())) - stop_words
    if not q_words:
        return 1.0

    p_words = set(re.findall(r'\w+', paragraph.lower()))
    match_count = len(q_words & p_words)
    return 1.0 + (match_count / len(q_words)) * 0.8


def extract_evidence_sentence(answer, context_chunk):
    if not answer or not context_chunk:
        return ""

    sentences = re.split(r'(?<=[.!?])\s+', context_chunk)
    for sent in sentences:
        if answer.lower() in sent.lower():
            return sent.strip()

    idx = context_chunk.lower().find(answer.lower())
    if idx != -1:
        start = max(0, idx - 80)
        end = min(len(context_chunk), idx + len(answer) + 80)
        prefix = "..." if start > 0 else ""
        suffix = "..." if end < len(context_chunk) else ""
        return prefix + context_chunk[start:end].strip() + suffix

    return context_chunk[:250] + "..."


