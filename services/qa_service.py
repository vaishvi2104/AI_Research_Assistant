def ask_question(question, context, use_web_search=False, paper_title="Paper"):
    """
    Production-grade Document-Wide RAG + Web Search Copilot:
    1. Checks for high-level academic prompt templates (contributions, beginner explanation, lit review).
    2. Performs dense semantic search + keyword overlap ranking.
    3. Runs DistilBERT Question-Answering.
    4. Optionally augments with live web / arXiv scientific search if enabled or document match is low.
    """
    if not question or not question.strip():
        return {
            "answer": "Please enter a specific research question to search the paper.",
            "context": None,
            "confidence": None,
            "badge_class": "badge-blue",
            "score": 0.0
        }

    question = question.strip()
    q_lower = question.lower()

    # 1. Check for predefined academic action prompts
    special_res = handle_special_research_prompts(q_lower, context, title=paper_title)
    if special_res:
        return {
            "answer": special_res["answer"],
            "context": special_res["evidence"],
            "confidence": special_res["confidence"],
            "badge_class": special_res["badge_class"],
            "score": special_res["score"]
        }

    # 2. If Web Search Mode is explicitly enabled
    if use_web_search:
        web_results = search_web_topic(question, max_results=3)
        if web_results:
            formatted_ans = f"**Live Academic & Web Search Findings for: *\"{question}\"***\n\n"
            for idx, item in enumerate(web_results, 1):
                formatted_ans += f"{idx}. **[{item['title']}]({item['url']})** ({item['year']})  \n"
                formatted_ans += f"   *Authors:* {item['authors']}  \n"
                formatted_ans += f"   {item['snippet']}\n\n"
            
            return {
                "answer": formatted_ans,
                "context": f"Fetched live from {web_results[0]['source']} repository.",
                "confidence": "Live Web Search (100%)",
                "badge_class": "badge-purple",
                "score": 1.0
            }

    # 3. Document-Wide Semantic RAG
    if not context or len(context.strip()) < 30:
        return {
            "answer": "No readable text was found in this research paper. Please make sure the document has selectable text.",
            "context": None,
            "confidence": None,
            "badge_class": "badge-amber",
            "score": 0.0
        }

    paragraphs = extract_document_paragraphs(context, max_words=140, overlap_words=30)
    if not paragraphs:
        return {
            "answer": "Document text could not be segmented into paragraphs.",
            "context": None,
            "confidence": None,
            "badge_class": "badge-amber",
            "score": 0.0
        }

    try:
        embedder = get_embedder()
        qa_pipe = get_qa_pipeline()
    except Exception as e:
        return {
            "answer": f"Error loading QA models: {e}",
            "context": None,
            "confidence": "Error",
            "badge_class": "badge-amber",
            "score": 0.0
        }

    # Semantic search across all document passages
    try:
        corpus_embeddings = embedder.encode(paragraphs, convert_to_tensor=True, show_progress_bar=False)
        query_embedding = embedder.encode(question, convert_to_tensor=True, show_progress_bar=False)
        
        top_k = min(4, len(paragraphs))
        hits = util.semantic_search(query_embedding, corpus_embeddings, top_k=top_k)[0]
    except Exception as e:
        hits = [{'corpus_id': i, 'score': 0.5} for i in range(min(4, len(paragraphs)))]

    best_answer = None
    best_final_score = -1.0
    best_qa_score = 0.0
    best_paragraph = None

    for hit in hits:
        idx = hit['corpus_id']
        sim_score = max(0.01, float(hit['score']))
        candidate_p = paragraphs[idx]

        try:
            res = qa_pipe(question=question, context=candidate_p)
            qa_score = float(res.get("score", 0.0))
            ans = res.get("answer", "").strip()

            kw_factor = get_keyword_overlap_factor(question, candidate_p)
            final_score = qa_score * sim_score * kw_factor

            if ans and len(ans) >= 2 and final_score > best_final_score:
                best_final_score = final_score
                best_qa_score = qa_score
                best_answer = ans
                best_paragraph = candidate_p
        except Exception:
            continue

    if not best_answer or best_final_score < 0.015:
        return {
            "answer": "I could not locate a direct answer to that question in the document. Try rephrasing or asking about methodology, datasets, models, or results.",
            "context": None,
            "confidence": "Low Confidence",
            "badge_class": "badge-amber",
            "score": best_qa_score
        }

    evidence = extract_evidence_sentence(best_answer, best_paragraph)

    if best_qa_score >= 0.5:
        confidence_text = f"High Confidence ({int(best_qa_score * 100)}%)"
        badge_class = "badge-emerald"
    elif best_qa_score >= 0.15:
        confidence_text = f"Moderate Confidence ({int(best_qa_score * 100)}%)"
        badge_class = "badge-blue"
    else:
        confidence_text = f"Estimated ({int(best_qa_score * 100)}%)"
        badge_class = "badge-amber"

    return {
        "answer": best_answer,
        "context": evidence,
        "confidence": confidence_text,
        "badge_class": badge_class,
        "score": best_qa_score
    }